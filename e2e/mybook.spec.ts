test('fixed visible rows shows the configured rows without clipping', async ({ page }) => {
  await signInForTest(page)
  await page.getByRole('button', { name: 'Create new' }).click()
  await page.getByRole('menuitem', { name: 'New document' }).click()

  const editor = page.getByRole('textbox', { name: 'Document content' })
  await editor.click()
  await page.getByRole('button', { name: 'Basic Table' }).click()
  const table = page.locator('.tiptap table')
  await expect(table).toBeVisible()
  await table.hover()
  const addRow = page.getByRole('button', { name: 'Add row', exact: true })
  for (let index = 0; index < 4; index += 1) await addRow.click({ force: true })
  await expect(table.locator('tr')).toHaveCount(6)
  await table.scrollIntoViewIfNeeded()
  await page.waitForTimeout(100)

  await page.getByRole('button', { name: 'Row 1 actions' }).evaluate((button) => (button as HTMLButtonElement).click())
  await page.getByRole('menuitemcheckbox', { name: 'Fixed visible rows' }).click()
  const tableWrapper = table.locator('xpath=..')
  const viewport = await tableWrapper.evaluate((wrapper) => {
    const rows = Array.from(wrapper.querySelectorAll('tr'))
    const fifthRow = rows[4]?.getBoundingClientRect()
    const wrapperRect = wrapper.getBoundingClientRect()
    return {
      fifthBottom: fifthRow?.bottom ?? 0,
      wrapperBottom: wrapperRect.bottom,
      clientHeight: wrapper.clientHeight,
      scrollHeight: wrapper.scrollHeight,
      style: wrapper.getAttribute('style'),
    }
  })
  expect(viewport.fifthBottom).toBeLessThanOrEqual(viewport.wrapperBottom + 1)
  expect(viewport.scrollHeight).toBeGreaterThan(viewport.clientHeight)
})

