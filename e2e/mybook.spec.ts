test('document table columns resize from dividers including the last column', async ({ page }) => {
  await signInForTest(page)
  await page.getByRole('button', { name: 'Create new' }).click()
  await page.getByRole('menuitem', { name: 'New document' }).click()

  const editor = page.getByRole('textbox', { name: 'Document content' })
  await editor.click()
  await page.getByRole('button', { name: 'Basic Table' }).click()
  const table = page.locator('.tiptap table')
  await expect(table).toBeVisible()
  const firstCell = table.locator('td').first()
  const firstCellBefore = await firstCell.boundingBox()
  if (!firstCellBefore) throw new Error('First column has no layout box')
  await page.mouse.move(firstCellBefore.x + firstCellBefore.width - 2, firstCellBefore.y + firstCellBefore.height / 2)
  const handles = page.locator('.column-resize-handle')
  await expect(handles).toHaveCount(2)
  const firstHandle = handles.nth(0)
  const firstHandleBox = await firstHandle.boundingBox()
  if (!firstHandleBox) throw new Error('First column resize handle has no layout box')
  await page.mouse.move(firstHandleBox.x + firstHandleBox.width / 2, firstHandleBox.y + firstHandleBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(firstHandleBox.x + 36, firstHandleBox.y + firstHandleBox.height / 2, { steps: 5 })
  await page.mouse.up()
  const firstCellAfter = await firstCell.boundingBox()
  if (!firstCellAfter) throw new Error('First column has no layout box after resize')
  expect(firstCellAfter.width).toBeGreaterThan(firstCellBefore.width + 20)

  const lastHandle = handles.nth(1)
  const lastHandleBox = await lastHandle.boundingBox()
  const lastCellBefore = await table.locator('td').nth(1).boundingBox()
  if (!lastHandleBox || !lastCellBefore) throw new Error('Last column resize handle has no layout box')
  await page.mouse.move(lastHandleBox.x + lastHandleBox.width / 2, lastHandleBox.y + lastHandleBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(lastHandleBox.x - 24, lastHandleBox.y + lastHandleBox.height / 2, { steps: 5 })
  await page.mouse.up()
  const lastCellAfter = await table.locator('td').nth(1).boundingBox()
  if (!lastCellAfter) throw new Error('Last column has no layout box after resize')
  expect(lastCellAfter.width).toBeGreaterThan(lastCellBefore.width + 12)
})

